#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md: every package that ships in a production
 * install, its version and licence, and the licence text itself, plus the
 * Codex icons that are vendored into src/.
 *
 *   npm run licenses
 *
 * Run it after changing dependencies and commit the result. CI checks that the
 * production tree contains no licence outside the allow-list below.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

// Permissive licences compatible with distributing WikiFrames under MIT.
// LGPL-3.0 appears only for libvips, which sharp loads as a separate,
// unmodified shared library (permitted by the LGPL).
const ALLOWED = new Set([
  'MIT',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'Apache-2.0',
  '0BSD',
  'CC0-1.0',
  'BlueOak-1.0.0',
  'Python-2.0',
  'Unlicense',
  'LGPL-3.0-or-later',
  'MIT OR Apache-2.0',
  '(MIT OR CC0-1.0)',
  'Apache-2.0 AND LGPL-3.0-or-later',
  'Apache-2.0 AND LGPL-3.0-or-later AND MIT',
  'MIT-0',
  // Browser-support data used at build time; attribution is given in the notices file.
  'CC-BY-4.0',
  // Dual/multi-licensed packages, used under the MIT option.
  '(MIT OR WTFPL)',
  '(BSD-2-Clause OR MIT OR Apache-2.0)',
]);

function licenseText(dir) {
  if (!fs.existsSync(dir)) return null;
  const file = fs
    .readdirSync(dir)
    .find((f) => /^(licen[cs]e|copying)(\.|-|$)/i.test(f) && fs.statSync(path.join(dir, f)).isFile());
  return file ? fs.readFileSync(path.join(dir, file), 'utf8').trim() : null;
}

const packages = [];
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev || meta.devOptional || meta.extraneous) continue;
  const dir = path.join(root, key);
  if (!fs.existsSync(dir)) continue; // optional platform binary for another OS
  const name = key.slice(key.lastIndexOf('node_modules/') + 'node_modules/'.length);
  const license = typeof meta.license === 'string' ? meta.license : meta.license?.type || 'UNKNOWN';
  packages.push({ name, version: meta.version, license, text: licenseText(dir) });
}
packages.sort((a, b) => a.name.localeCompare(b.name));

const unknown = packages.filter((p) => !ALLOWED.has(p.license));
if (process.argv.includes('--check')) {
  if (unknown.length) {
    console.error('Licences outside the allow-list:');
    for (const p of unknown) console.error(`  ${p.name}@${p.version}: ${p.license}`);
    process.exit(1);
  }
  console.log(`✓ ${packages.length} production packages, all with allowed licences`);
  process.exit(0);
}

const codexLicense = fs
  .readFileSync(path.join(root, 'src/components/icons/codex.js'), 'utf8')
  .match(/\* MIT License[\s\S]*?WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE\./)?.[0]
  .split('\n')
  .map((l) => l.replace(/^ \* ?/, ''))
  .join('\n');

const byLicense = packages.reduce((acc, p) => {
  (acc[p.license] ||= []).push(p);
  return acc;
}, {});

const lines = [
  '# Third-party notices',
  '',
  'WikiFrames itself is released under the MIT License (see `LICENSE`).',
  'It is distributed together with the third-party software listed below, each',
  'under its own licence. This file is generated by `npm run licenses`.',
  '',
  '## Summary',
  '',
  '| Licence | Packages |',
  '|---|---|',
  ...Object.entries(byLicense)
    .sort((a, b) => b[1].length - a[1].length)
    .map(([license, list]) => `| ${license} | ${list.length} |`),
  '',
  '## Vendored code',
  '',
  '### Codex icons — `src/components/icons/codex.js`',
  '',
  'A subset of [@wikimedia/codex-icons](https://doc.wikimedia.org/codex/latest/icons/all-icons.html) 2.7.0,',
  'the icon set of the Wikimedia Design System. Only generic interface icons are',
  'included; no Wikimedia logos or other trademarks.',
  '',
  '```',
  codexLicense || 'MIT License',
  '```',
  '',
  '### Native libraries',
  '',
  '`sharp` ships prebuilt binaries of **libvips** (LGPL-3.0-or-later) and the image',
  'libraries it links against (libjpeg-turbo, libpng, libwebp, librsvg, cairo,',
  'pango, HarfBuzz, fontconfig and others), as dynamically linked shared libraries',
  'in the `@img/sharp-libvips-*` packages. Their licences are listed in those',
  'packages. Under the LGPL you may replace them with your own build.',
  '',
  '## Packages',
  '',
];

for (const p of packages) {
  lines.push(`### ${p.name}@${p.version} — ${p.license}`, '');
  if (p.text) lines.push('```', p.text, '```', '');
  else lines.push('_No licence file shipped; see the package metadata._', '');
}

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), `${lines.join('\n')}\n`);
console.log(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages)`);
if (unknown.length) {
  console.warn('Review these licences:');
  for (const p of unknown) console.warn(`  ${p.name}@${p.version}: ${p.license}`);
}
