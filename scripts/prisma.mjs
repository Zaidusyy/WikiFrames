#!/usr/bin/env node
// Runs the Prisma CLI against the database WikiFrames is configured for.
//
//   node scripts/prisma.mjs generate
//   node scripts/prisma.mjs db push --skip-generate
//
// prisma/schema.prisma is written for PostgreSQL. For MariaDB/MySQL (such as
// Toolforge's ToolsDB) a copy with the provider swapped is written to
// prisma/generated/ and used instead — the rest of the schema is shared.
// The provider is DATABASE_PROVIDER ("postgresql" or "mysql") when set, else
// read from the scheme of DATABASE_URL, else PostgreSQL.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export function databaseProvider(env = process.env) {
  const explicit = (env.DATABASE_PROVIDER || '').trim().toLowerCase();
  if (explicit === 'mysql' || explicit === 'mariadb') return 'mysql';
  if (explicit === 'postgresql' || explicit === 'postgres') return 'postgresql';
  if (explicit) throw new Error(`DATABASE_PROVIDER must be "postgresql" or "mysql", not "${explicit}".`);
  return /^(mysql|mariadb):/i.test(env.DATABASE_URL || '') ? 'mysql' : 'postgresql';
}

/** Path of the schema to hand to Prisma, writing the MySQL variant if needed. */
export function schemaFor(provider) {
  const source = path.join(root, 'prisma', 'schema.prisma');
  if (provider === 'postgresql') return source;
  const schema = fs.readFileSync(source, 'utf8');
  const swapped = schema.replace(/(datasource db \{\s*provider\s*=\s*)"postgresql"/, `$1"${provider}"`);
  if (swapped === schema) throw new Error('Could not find the datasource provider in prisma/schema.prisma.');
  const target = path.join(root, 'prisma', 'generated', `schema.${provider}.prisma`);
  const content = `// Generated by scripts/prisma.mjs from prisma/schema.prisma — do not edit.\n${swapped}`;
  // Written at build time; at runtime the app directory may be read-only.
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
  return target;
}

function main(args) {
  const provider = databaseProvider();
  const schema = schemaFor(provider);
  const cli = path.join(root, 'node_modules', 'prisma', 'build', 'index.js');
  const result = spawnSync(process.execPath, [cli, ...args, '--schema', schema], { stdio: 'inherit', cwd: root });
  process.exit(result.status ?? 1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
