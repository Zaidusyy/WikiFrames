import archiver from 'archiver';
import { PassThrough, Readable } from 'node:stream';
import { config } from '@/lib/config';
import { prisma } from '@/lib/db';
import { handler } from '@/lib/api';
import { requireUser } from '@/lib/session';
import { loadCampaignFor } from '@/lib/authz';
import { enforce } from '@/lib/ratelimit';
import { getObject } from '@/lib/storage';
import { slugify } from '@/lib/tokens';

export const dynamic = 'force-dynamic';
export const maxDuration = 300;

const PAGE = 100;

// GAL-2 / RET-5: bulk ZIP download so organizers keep their own record before
// the retention window closes. Streamed, because a large conference gallery is
// hundreds of megabytes and must never be buffered in memory:
//   - images are read one at a time, and the next one is only fetched after
//     the archive has consumed the previous one;
//   - JPEG/PNG are already compressed, so entries are stored, not deflated;
//   - if the browser goes away, the work stops instead of reading every image
//     in the campaign into nowhere.
export const GET = handler(async (req, { params }) => {
  const user = await requireUser();
  const { id } = await params;
  const { campaign } = await loadCampaignFor(user, id);
  enforce(`export:${user.id}`, 20);

  const total = await prisma.generatedImage.count({ where: { campaignId: campaign.id } });

  const archive = archiver('zip', { zlib: { level: 6 } });
  const passthrough = new PassThrough({ highWaterMark: 1024 * 1024 });
  archive.pipe(passthrough);

  let aborted = false;
  const abort = () => {
    aborted = true;
    archive.abort();
  };
  req.signal?.addEventListener('abort', abort, { once: true });
  archive.on('error', (err) => {
    aborted = true;
    console.error('[gallery-export] archive failed', err.message);
    passthrough.destroy(err);
  });

  archive.append(
    [
      `Campaign: ${campaign.name}`,
      `Event: ${campaign.eventDate.toISOString()} → ${campaign.eventEndDate.toISOString()}`,
      `Images: ${total}`,
      `Exported: ${new Date().toISOString()}`,
      '',
      'These images were generated by participants who consented to storage.',
      `WikiFrames deletes its own copies ${config.retention.days} days after the event ends — keeping`,
      'this archive, and honouring the same promise, is now your responsibility.',
    ].join('\n'),
    { name: 'README.txt' }
  );

  (async () => {
    let index = 0;
    let cursor;
    try {
      while (!aborted) {
        const images = await prisma.generatedImage.findMany({
          where: { campaignId: campaign.id },
          orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
          take: PAGE,
          ...(cursor ? { cursor: { id: cursor }, skip: 1 } : {}),
          include: {
            asset: { select: { storageKey: true, mime: true } },
            role: { select: { label: true } },
          },
        });
        if (!images.length) break;

        for (const image of images) {
          if (aborted) break;
          index += 1;
          try {
            const buffer = await getObject(image.asset.storageKey);
            const ext = image.asset.mime === 'image/jpeg' ? 'jpg' : 'png';
            const rolePart = image.role?.label ? `-${slugify(image.role.label, { maxLength: 40 })}` : '';
            const entryDone = nextEntry(archive);
            archive.append(buffer, {
              name: `${String(index).padStart(4, '0')}${rolePart}.${ext}`,
              date: image.createdAt,
              store: true,
            });
            await entryDone;
            // Backpressure: wait while the client is slower than storage.
            if (passthrough.writableNeedDrain) {
              await new Promise((resolve) => passthrough.once('drain', resolve));
            }
          } catch (err) {
            console.error('[gallery-export] skipped image', image.id, err.message);
          }
        }
        cursor = images[images.length - 1].id;
        if (images.length < PAGE) break;
      }
      if (!aborted) await archive.finalize();
    } catch (err) {
      console.error('[gallery-export] failed', err.message);
      passthrough.destroy(err);
    } finally {
      req.signal?.removeEventListener('abort', abort);
    }
  })();

  const filename = `${slugify(campaign.name)}-gallery.zip`;
  // The Fetch Response body must be a web stream, not a Node one.
  return new Response(Readable.toWeb(passthrough), {
    headers: {
      'Content-Type': 'application/zip',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store',
    },
  });
});

/** Resolves when the archive has consumed the entry just appended. */
function nextEntry(archive) {
  return new Promise((resolve, reject) => {
    const onEntry = () => {
      archive.off('error', onError);
      resolve();
    };
    const onError = (err) => {
      archive.off('entry', onEntry);
      reject(err);
    };
    archive.once('entry', onEntry);
    archive.once('error', onError);
  });
}
