import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from './config';
import { prisma } from './db';
import { SIGNED_PURPOSE, signValue } from './signing';
import { randomToken } from './tokens';

// Object storage abstraction (PDR §5.2). The `local` driver keeps everything on
// disk so the product runs without cloud credentials; the `s3` driver is the
// deployment target where the 30-day lifecycle rule acts as the RET-4 safety net.
//
// The DB only ever holds metadata + a storage key, never bytes.

const localRoot = path.resolve(
  path.isAbsolute(config.storage.localRoot)
    ? config.storage.localRoot
    : path.join(process.cwd(), config.storage.localRoot)
);

const KEY_PATTERN = /^[a-z]+\/\d{6}\/[A-Za-z0-9_-]{8,64}\.[a-z0-9]{2,5}$/;

function localPath(key) {
  // Keys are generated by keyFor() below and never come from a request, but a
  // path is only ever built from something that looks exactly like one.
  if (!KEY_PATTERN.test(key)) throw new Error(`Refusing unexpected storage key: ${key}`);
  const full = path.resolve(localRoot, key);
  const relative = path.relative(localRoot, full);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error('Refusing to escape storage root');
  }
  return full;
}

async function putLocal(key, buffer) {
  const full = localPath(key);
  await fs.mkdir(path.dirname(full), { recursive: true });
  // Write-then-rename: a crash mid-write never leaves a truncated image behind
  // under the real key.
  const temp = `${full}.${randomToken(6)}.tmp`;
  await fs.writeFile(temp, buffer, { mode: 0o600 });
  await fs.rename(temp, full);
}

async function getLocal(key) {
  return fs.readFile(localPath(key));
}

async function delLocal(key) {
  await fs.rm(localPath(key), { force: true });
}

// Indirection on purpose: the bundler must not try to resolve the AWS SDK at
// build time. It is an optional peer — installed only when STORAGE_DRIVER=s3 —
// so a literal import path would make the local driver fail to compile.
const S3_SDK = '@aws-sdk/client-s3';
const importS3 = (name) => import(/* webpackIgnore: true */ name);

let s3Client = null;
async function getS3() {
  if (s3Client) return s3Client;
  const { S3Client } = await importS3(S3_SDK);
  s3Client = new S3Client({
    region: config.storage.s3.region,
    endpoint: config.storage.s3.endpoint || undefined,
    forcePathStyle: Boolean(config.storage.s3.endpoint),
    credentials: {
      accessKeyId: config.storage.s3.accessKeyId,
      secretAccessKey: config.storage.s3.secretAccessKey,
    },
  });
  return s3Client;
}

export async function putObject(key, buffer, mime) {
  if (config.storage.driver === 's3') {
    const { PutObjectCommand } = await importS3(S3_SDK);
    const client = await getS3();
    await client.send(
      new PutObjectCommand({
        Bucket: config.storage.s3.bucket,
        Key: key,
        Body: buffer,
        ContentType: mime,
      })
    );
    return key;
  }
  await putLocal(key, buffer);
  return key;
}

export async function getObject(key) {
  if (config.storage.driver === 's3') {
    const { GetObjectCommand } = await importS3(S3_SDK);
    const client = await getS3();
    const out = await client.send(
      new GetObjectCommand({ Bucket: config.storage.s3.bucket, Key: key })
    );
    return Buffer.from(await out.Body.transformToByteArray());
  }
  return getLocal(key);
}

export async function deleteObject(key) {
  if (config.storage.driver === 's3') {
    const { DeleteObjectCommand } = await importS3(S3_SDK);
    const client = await getS3();
    await client.send(
      new DeleteObjectCommand({ Bucket: config.storage.s3.bucket, Key: key })
    );
    return;
  }
  await delLocal(key);
}

const EXT_BY_MIME = {
  'image/png': 'png',
  'image/jpeg': 'jpg',
  'image/webp': 'webp',
  'application/zip': 'zip',
  'application/pdf': 'pdf',
};

export function keyFor(kind, mime) {
  const ext = EXT_BY_MIME[mime] || 'bin';
  const now = new Date();
  const yyyymm = `${now.getUTCFullYear()}${String(now.getUTCMonth() + 1).padStart(2, '0')}`;
  return `${kind}/${yyyymm}/${randomToken(12)}.${ext}`;
}

/** Stores bytes and records the accompanying `assets` row in one step. */
export async function storeAsset({ kind, mime, buffer, width, height, ownerId }) {
  const key = keyFor(kind, mime);
  await putObject(key, buffer, mime);
  try {
    return await prisma.asset.create({
      data: {
        storageKey: key,
        mime,
        bytes: buffer.length,
        width: width ?? null,
        height: height ?? null,
        kind,
        ownerId: ownerId ?? null,
      },
    });
  } catch (err) {
    // No row means nothing would ever find these bytes to delete them.
    await deleteObject(key).catch(() => {});
    throw err;
  }
}

/**
 * Hard-deletes bytes, then metadata.
 *
 * If the bytes cannot be deleted (storage outage, permissions), the row is
 * kept on purpose: it is the only record that the bytes still exist, and the
 * retention job's orphan sweep retries until the deletion succeeds. Dropping
 * the row anyway — as this used to — silently broke the deletion promise.
 */
export async function destroyAsset(assetId) {
  const asset = await prisma.asset.findUnique({ where: { id: assetId } });
  if (!asset) return true;
  try {
    await deleteObject(asset.storageKey);
  } catch (err) {
    console.error(`[storage] could not delete bytes for asset=${asset.id}; will retry`, err.message);
    return false;
  }
  await prisma.asset.delete({ where: { id: assetId } }).catch(() => {});
  return true;
}

/**
 * Every asset is served through our own route so access rules stay in one
 * place. Generated (participant) images additionally need either a session
 * with access to the campaign, a public gallery, or the signature minted here.
 */
export function assetUrl(assetId, { signedForSeconds } = {}) {
  const base = `/api/v1/assets/${assetId}`;
  if (!signedForSeconds) return base;
  return `${base}?t=${signValue(SIGNED_PURPOSE.ASSET, assetId, signedForSeconds)}`;
}
