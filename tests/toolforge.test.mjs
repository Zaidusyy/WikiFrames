import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';

// Toolforge mode: the front proxy hides visitor addresses. Set before the
// modules that read config are loaded (each test file runs in its own process).
process.env.CLIENT_IP_HIDDEN = 'true';

const { databaseProvider, schemaFor } = await import('../scripts/prisma.mjs');
const { perIpLimit } = await import('../src/lib/api.js');
const { assertAccessCode } = await import('../src/lib/participant.js');
const { resetRateLimits } = await import('../src/lib/ratelimit.js');

test('the database provider follows DATABASE_PROVIDER, then the URL scheme', () => {
  assert.equal(databaseProvider({}), 'postgresql');
  assert.equal(databaseProvider({ DATABASE_URL: 'postgresql://u:p@h/db' }), 'postgresql');
  assert.equal(databaseProvider({ DATABASE_URL: 'mysql://u:p@tools.db.svc.wikimedia.cloud/s1__wikiframes' }), 'mysql');
  assert.equal(databaseProvider({ DATABASE_PROVIDER: 'mariadb', DATABASE_URL: 'postgresql://x' }), 'mysql');
  assert.throws(() => databaseProvider({ DATABASE_PROVIDER: 'sqlite' }), /must be/);
});

test('the MySQL schema differs from the PostgreSQL one only in its provider', () => {
  const pg = fs.readFileSync(schemaFor('postgresql'), 'utf8');
  const mysql = fs.readFileSync(schemaFor('mysql'), 'utf8');
  assert.match(pg, /provider = "postgresql"/);
  assert.match(mysql, /provider = "mysql"/);
  const strip = (s) => s.replace(/^\/\/ Generated by.*\n/, '').replace(/provider = "(postgresql|mysql)"/, '');
  assert.equal(strip(mysql), strip(pg));
});

test('with hidden addresses, per-address limits are sized for a whole venue', () => {
  assert.equal(perIpLimit(60), 3000);
});

test('with hidden addresses, wrong access codes count per campaign, not per address', () => {
  resetRateLimits();
  const campaign = { id: 'c1', accessCode: '4821' };
  // Well past the per-address allowance (30): one shared address must not lock the venue out.
  for (let i = 0; i < 40; i += 1) {
    assert.throws(() => assertAccessCode(campaign, '0000', 'shared'), /not right/);
  }
  assert.doesNotThrow(() => assertAccessCode(campaign, '4821', 'shared'));
  // The campaign-wide budget (300) still stops a brute force.
  for (let i = 0; i < 260; i += 1) {
    try {
      assertAccessCode(campaign, '0000', 'shared');
    } catch {
      // expected
    }
  }
  assert.throws(() => assertAccessCode(campaign, '4821', 'shared'), /Too many wrong codes/);
});
